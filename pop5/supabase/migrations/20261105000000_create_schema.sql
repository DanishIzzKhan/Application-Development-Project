-- Bicycle and Scooter Rental System: initial schema (PostgreSQL / Supabase)
-- Charging model: customers pay per 20-minute block, with a grace period.
-- Note: the Supabase CLI runs each migration inside a transaction, so no BEGIN/COMMIT here.

-- ---------------------------------------------------------------
-- USERS
-- ---------------------------------------------------------------
CREATE TABLE users (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    full_name      varchar(100) NOT NULL,
    username       varchar(50)  NOT NULL UNIQUE,          -- profile name
    email          varchar(255) NOT NULL UNIQUE,
    password_hash  varchar(255) NOT NULL,
    phone          varchar(20)  UNIQUE,
    role           varchar(10)  NOT NULL DEFAULT 'customer'
                   CHECK (role IN ('customer', 'owner')),
    fcm_token      varchar(255),                          -- push notification token (one device)
    created_at     timestamptz  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------
-- VEHICLES
-- ---------------------------------------------------------------
CREATE TABLE vehicles (
    id                 varchar(20) PRIMARY KEY,           -- e.g. BK-01, SC-02
    type               varchar(10) NOT NULL
                       CHECK (type IN ('Bicycle', 'Scooter')),
    status             varchar(15) NOT NULL DEFAULT 'Available'
                       CHECK (status IN ('Available', 'Rented', 'Maintenance')),
    rate_per_block     numeric(8,2) NOT NULL CHECK (rate_per_block >= 0),  -- price per 20-minute block
    total_distance_km  numeric(10,2) NOT NULL DEFAULT 0 CHECK (total_distance_km >= 0),  -- AI metric
    total_ride_hours   numeric(10,2) NOT NULL DEFAULT 0 CHECK (total_ride_hours >= 0),   -- AI metric
    last_service_date  date,                              -- service age is calculated from this
    reported_issues    integer NOT NULL DEFAULT 0 CHECK (reported_issues >= 0),          -- AI metric
    is_active          boolean NOT NULL DEFAULT true      -- false = soft-deleted
);

-- ---------------------------------------------------------------
-- PAYMENT_METHODS (saved card for auto-charging late blocks)
-- ---------------------------------------------------------------
CREATE TABLE payment_methods (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id        uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    gateway_token  varchar(255) NOT NULL,                 -- token from the payment gateway, never the card number
    brand          varchar(20),
    last4          char(4) CHECK (last4 ~ '^[0-9]{4}$'),
    is_default     boolean NOT NULL DEFAULT false
);

-- at most one default card per user
CREATE UNIQUE INDEX uq_payment_methods_default
    ON payment_methods (user_id) WHERE is_default;

-- ---------------------------------------------------------------
-- RENTALS
-- ---------------------------------------------------------------
CREATE TABLE rentals (
    id                        varchar(20) PRIMARY KEY,    -- e.g. RNT-8801 (generated by the API)
    customer_id               uuid REFERENCES users(id),  -- NULL for walk-in customers
    payment_method_id         uuid REFERENCES payment_methods(id) ON DELETE SET NULL,
    vehicle_id                varchar(20) NOT NULL REFERENCES vehicles(id),

    booking_code              varchar(20) NOT NULL UNIQUE,
    qr_token                  varchar(100) NOT NULL UNIQUE,  -- scanned at collection

    is_walk_in                boolean NOT NULL DEFAULT false,
    walk_in_name              varchar(100),
    walk_in_phone             varchar(20),
    deposit_note              text,
    is_tracked                boolean NOT NULL DEFAULT true,

    scheduled_start_time      timestamptz NOT NULL,
    actual_start_time         timestamptz,                -- set at vehicle collection
    original_end_time         timestamptz NOT NULL,       -- never changes
    scheduled_end_time        timestamptz NOT NULL,       -- moves when extended
    actual_end_time           timestamptz,                -- set at vehicle return

    blocks_booked             integer NOT NULL CHECK (blocks_booked > 0),
    rate_per_block_at_booking numeric(8,2) NOT NULL CHECK (rate_per_block_at_booking >= 0),
    grace_minutes_at_booking  integer NOT NULL CHECK (grace_minutes_at_booking >= 0),
    late_rate_at_booking      numeric(8,2) NOT NULL CHECK (late_rate_at_booking >= 0),
    late_blocks_charged       integer NOT NULL DEFAULT 0 CHECK (late_blocks_charged >= 0),
    auto_charge_stopped       boolean NOT NULL DEFAULT false,
    distance_km               numeric(8,2) NOT NULL DEFAULT 0 CHECK (distance_km >= 0),
    total_amount              numeric(10,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),

    status                    varchar(20) NOT NULL DEFAULT 'pending_payment'
                              CHECK (status IN ('pending_payment', 'ready', 'checked_in', 'active',
                                                'completed', 'cancelled', 'expired')),

    CONSTRAINT scheduled_window_valid  CHECK (scheduled_end_time > scheduled_start_time),
    CONSTRAINT customer_or_walk_in     CHECK (customer_id IS NOT NULL OR is_walk_in)
);

-- ---------------------------------------------------------------
-- PAYMENTS (a rental can have several: upfront, late blocks, extensions)
-- ---------------------------------------------------------------
CREATE TABLE payments (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    rental_id       varchar(20) NOT NULL REFERENCES rentals(id),
    refund_of       uuid REFERENCES payments(id),          -- set when this row refunds another payment
    confirmed_by    uuid REFERENCES users(id),             -- owner who confirmed a cash payment
    payment_method  varchar(10) NOT NULL
                    CHECK (payment_method IN ('TnG', 'Bank QR', 'Cash', 'Card')),  -- 'Card' = saved card auto-charge
    payment_type    varchar(15) NOT NULL DEFAULT 'upfront'
                    CHECK (payment_type IN ('upfront', 'late_block', 'extension')),
    is_auto         boolean NOT NULL DEFAULT false,        -- true = charged automatically
    amount          numeric(10,2) NOT NULL CHECK (amount >= 0),
    status          varchar(10) NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'completed', 'failed', 'refunded')),
    gateway_ref     varchar(100),                          -- NULL for cash
    receipt_no      varchar(30) UNIQUE,
    failure_reason  text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    paid_at         timestamptz
);

-- ---------------------------------------------------------------
-- EXTENSIONS (history of rental extensions)
-- ---------------------------------------------------------------
CREATE TABLE extensions (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    rental_id     varchar(20) NOT NULL REFERENCES rentals(id) ON DELETE CASCADE,
    old_end_time  timestamptz NOT NULL,
    new_end_time  timestamptz NOT NULL,
    blocks_added  integer NOT NULL CHECK (blocks_added > 0),
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT extension_moves_forward CHECK (new_end_time > old_end_time)
);

-- ---------------------------------------------------------------
-- LOCATION_LOGS (GPS route history)
-- ---------------------------------------------------------------
CREATE TABLE location_logs (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    rental_id    varchar(20) NOT NULL REFERENCES rentals(id) ON DELETE CASCADE,
    latitude     numeric(9,6) NOT NULL CHECK (latitude  BETWEEN -90  AND 90),
    longitude    numeric(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    recorded_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------
-- NOTIFICATIONS (replaces ALERTS: owner and customer notifications)
-- ---------------------------------------------------------------
CREATE TABLE notifications (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id     uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    rental_id   varchar(20) REFERENCES rentals(id) ON DELETE SET NULL,
    type        varchar(30) NOT NULL,        -- e.g. out_of_park, overdue, boundary_warning, lost_signal, late_charge
    title       varchar(150) NOT NULL,
    body        text,
    read_at     timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------
-- VEHICLE_CONDITION_CHECKS (digital handover)
-- ---------------------------------------------------------------
CREATE TABLE vehicle_condition_checks (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    rental_id    varchar(20) NOT NULL REFERENCES rentals(id) ON DELETE CASCADE,
    stage        varchar(10) NOT NULL CHECK (stage IN ('pickup', 'return')),
    condition    varchar(15) NOT NULL CHECK (condition IN ('Good', 'Minor issue', 'Damaged')),
    notes        text,
    photo_url    varchar(500),
    recorded_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (rental_id, stage)                              -- one check per stage per rental
);

-- ---------------------------------------------------------------
-- MAINTENANCE_LOGS (customer reports, service records, AI flags)
-- ---------------------------------------------------------------
CREATE TABLE maintenance_logs (
    id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    vehicle_id         varchar(20) NOT NULL REFERENCES vehicles(id),
    reported_by        uuid NOT NULL REFERENCES users(id),
    rental_id          varchar(20) REFERENCES rentals(id) ON DELETE SET NULL,  -- optional
    log_type           varchar(20) NOT NULL
                       CHECK (log_type IN ('customer_report', 'service', 'ai_flag')),
    issue_description  text NOT NULL,
    problem_found      boolean,                            -- training label for the AI model (NULL = not checked yet)
    cost               numeric(10,2) CHECK (cost >= 0),
    status             varchar(10) NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending', 'resolved')),
    ai_risk_score      integer CHECK (ai_risk_score BETWEEN 0 AND 100),        -- score at time of flag
    created_at         timestamptz NOT NULL DEFAULT now(),
    resolved_at        timestamptz
);

-- ---------------------------------------------------------------
-- MAINTENANCE_PREDICTIONS (output of the Random Forest model)
-- ---------------------------------------------------------------
CREATE TABLE maintenance_predictions (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    vehicle_id      varchar(20) NOT NULL REFERENCES vehicles(id),
    risk_score      integer NOT NULL CHECK (risk_score BETWEEN 0 AND 100),
    priority_level  varchar(6) NOT NULL CHECK (priority_level IN ('HIGH', 'MEDIUM', 'LOW')),
    reasons         text,
    model_version   varchar(30) NOT NULL,
    predicted_at    timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------
-- SHOP_SETTINGS (owner-editable rules; always exactly one row)
-- ---------------------------------------------------------------
CREATE TABLE shop_settings (
    id                 smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    grace_minutes      integer NOT NULL DEFAULT 5 CHECK (grace_minutes >= 0),
    late_rate          numeric(8,2) NOT NULL DEFAULT 0 CHECK (late_rate >= 0),  -- price per late 20-minute block
    auto_charge_limit  integer NOT NULL DEFAULT 3 CHECK (auto_charge_limit >= 0),
    updated_at         timestamptz NOT NULL DEFAULT now()
);

INSERT INTO shop_settings (id) VALUES (1);   -- late_rate = 0 until the owner sets it

-- ---------------------------------------------------------------
-- PARK_BOUNDARY (geofence polygon for Kulai Park)
-- ---------------------------------------------------------------
CREATE TABLE park_boundary (
    id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name              varchar(100) NOT NULL,
    boundary_geojson  jsonb NOT NULL,
    updated_at        timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------
-- INDEXES
-- ---------------------------------------------------------------
CREATE INDEX idx_rentals_customer      ON rentals (customer_id);
CREATE INDEX idx_rentals_vehicle       ON rentals (vehicle_id);
CREATE INDEX idx_rentals_status        ON rentals (status);
CREATE INDEX idx_rentals_pay_method    ON rentals (payment_method_id);
CREATE INDEX idx_payments_rental       ON payments (rental_id);
CREATE INDEX idx_payments_gateway_ref  ON payments (gateway_ref);
CREATE INDEX idx_payment_methods_user  ON payment_methods (user_id);
CREATE INDEX idx_extensions_rental     ON extensions (rental_id);
CREATE INDEX idx_location_rental_time  ON location_logs (rental_id, recorded_at);
CREATE INDEX idx_notif_user_unread     ON notifications (user_id, created_at DESC) WHERE read_at IS NULL;
CREATE INDEX idx_notif_rental          ON notifications (rental_id);
CREATE INDEX idx_maint_vehicle         ON maintenance_logs (vehicle_id);
CREATE INDEX idx_maint_reported_by     ON maintenance_logs (reported_by);
CREATE INDEX idx_maint_rental          ON maintenance_logs (rental_id);
CREATE INDEX idx_pred_vehicle_time     ON maintenance_predictions (vehicle_id, predicted_at DESC);

-- ---------------------------------------------------------------
-- VIEW: latest prediction per active vehicle (owner's maintenance priority ranking)
-- ---------------------------------------------------------------
CREATE VIEW vehicle_maintenance_priority
WITH (security_invoker = true) AS
SELECT DISTINCT ON (p.vehicle_id)
       p.vehicle_id,
       v.type,
       v.status,
       p.risk_score,
       p.priority_level,
       p.reasons,
       p.model_version,
       p.predicted_at
FROM maintenance_predictions p
JOIN vehicles v ON v.id = p.vehicle_id
WHERE v.is_active
ORDER BY p.vehicle_id, p.predicted_at DESC;

